const CHAVE = 'pedraverde:idioma';

export function lerIdioma() {
  try { return localStorage.getItem(CHAVE) || 'pt'; } catch { return 'pt'; }
}
export function gravarIdioma(l) {
  try { localStorage.setItem(CHAVE, l); } catch {}
}

export function traduzir(idioma, chave, vars = {}) {
  const t = TRADUCOES[idioma] || TRADUCOES.pt;
  let s = t[chave] || TRADUCOES.pt[chave] || chave;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(`{${k}}`, v);
  }
  return s;
}

